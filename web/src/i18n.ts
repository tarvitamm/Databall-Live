export type Strings = (typeof UI)['en']

export function strings(lang: Lang): Strings {
  return UI[lang] as unknown as Strings
}

export function stateLabel(label: string, s: Strings): string {
  if (label === 'balanced') return s.balanced
  if (label === 'chaotic') return s.chaotic
  return label.replace('in control', s.inControl)
}

export function clock(period: number, t: number): string {
  const base = period === 1 ? 45 : 90
  const minute = Math.floor(t / 60)
  if (minute >= base) return `${base}+${minute - base + 1}'`
  return `${minute + 1}'`
}

export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ''))
}
